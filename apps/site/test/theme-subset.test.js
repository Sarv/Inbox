import postcss from 'postcss';
import { describe, expect, it } from 'vitest';

import {
  THEME_SELECTORS,
  buildThemeSubset,
  definedClasses,
  referencedTokens,
  tokenClosure,
} from '../scripts/theme-subset.mjs';

// A miniature sarv_theme: enough to exercise every path without the real file,
// which lives in a private repository CI cannot read.
const DESIGN_SYSTEM = `
:root {
  --color-brand-500: #3069B0;
  --color-unused: #000000;
  --brand: var(--color-brand-500);
  --space-3: 12px;
  --space-9: 48px;
}
:root { --space-3: 14px; }
.dark {
  --brand: #5B92D2;
  --color-unused: #111111;
}
.btn { color: var(--brand); padding: var(--space-3); }
.btn:hover { color: var(--brand); }
.table { border: 1px solid var(--color-unused); }
@media (max-width: 600px) { .btn { padding: 0; } }
`;
const FONTS = "@import url('https://fonts.example/css?family=Jakarta');\n";
const PAGE = '.page { margin: var(--space-9); }';

const subset = (overrides = {}) =>
  buildThemeSubset({
    designSystemCss: DESIGN_SYSTEM,
    fontsCss: FONTS,
    pageCss: PAGE,
    selectors: ['.btn'],
    ...overrides,
  });

const tokensOf = (css, scope) =>
  postcss
    .parse(css)
    .nodes.filter((node) => node.type === 'rule' && node.selector === scope)
    .flatMap((rule) => rule.nodes.map((decl) => `${decl.prop}: ${decl.value}`));

describe('buildThemeSubset', () => {
  // Breaks if the subset drops the component rules the page asked for, or leaks others.
  it('copies only the listed top-level rules, verbatim and in source order', () => {
    const css = subset({ selectors: ['.btn:hover', '.btn'] });
    expect(css).toContain('.btn { color: var(--brand); padding: var(--space-3); }');
    expect(css.indexOf('.btn {')).toBeLessThan(css.indexOf('.btn:hover {'));
    expect(css).not.toContain('.table');
    expect(css).not.toContain('@media');
  });

  // Breaks if a token reached only through another token (--brand -> --color-brand-500)
  // is dropped: the button would render with an unset colour.
  it('keeps the tokens the rules and the page reach, transitively, and no others', () => {
    const css = subset();
    expect(tokensOf(css, ':root')).toEqual([
      '--color-brand-500: #3069B0',
      '--brand: var(--color-brand-500)',
      '--space-3: 14px',
      '--space-9: 48px',
    ]);
    expect(css).not.toContain('--color-unused');
  });

  // Breaks if dark-mode overrides leak into the page, which is light-only by design.
  it("leaves sarv_theme's .dark overrides behind", () => {
    expect(subset()).not.toContain('.dark');
  });

  // Breaks if the fonts stop loading, or the generated-file warning goes missing.
  it('starts with the header and the fonts import', () => {
    const css = subset();
    expect(css.startsWith('/* GENERATED by scripts/sync-theme.mjs')).toBe(true);
    expect(css).toContain("@import url('https://fonts.example/css?family=Jakarta');");
    expect(css.indexOf('@import')).toBeLessThan(css.indexOf(':root'));
  });

  // Breaks if a class renamed in sarv_theme silently drops its styles from the page.
  it('throws on a selector sarv_theme does not have', () => {
    expect(() => subset({ selectors: ['.btn', '.btn-ghost'] })).toThrow(
      'sarv_theme has no rule for: .btn-ghost'
    );
  });

  // Breaks if the page reads a token sarv_theme never defines and the sync lets it through.
  it('throws on a token nobody defines', () => {
    expect(() => subset({ pageCss: '.page { gap: var(--space-99); }' })).toThrow(
      'sarv_theme defines no --space-99'
    );
  });

  // Breaks if a re-run changes the output, which would churn the committed file.
  it('is deterministic', () => {
    expect(subset()).toBe(subset());
  });
});

describe('helpers', () => {
  // Breaks if var() fallbacks or nested var()s hide a token from the closure.
  it('referencedTokens finds nested and fallback var()s and ignores an empty var()', () => {
    const root = postcss.parse(
      'a { color: var(--a, var(--b)); margin: calc(var(--c) * 2); x: var(); }'
    );
    expect([...referencedTokens(root)].sort()).toEqual(['--a', '--b', '--c']);
  });

  // Breaks if a compound or pseudo selector hides one of its classes.
  it('definedClasses reads every class in a selector list', () => {
    const root = postcss.parse(
      '.btn.btn-lg:hover, .card > .row { x: 1 } @media (x) { .stack { x: 1 } }'
    );
    expect([...definedClasses(root)].sort()).toEqual(['btn', 'btn-lg', 'card', 'row', 'stack']);
  });

  // Breaks if a token cycle or shared dependency loops forever or is counted twice.
  it('tokenClosure terminates on shared and cyclic references', () => {
    const scope = new Map([
      ['--a', 'var(--b) var(--c)'],
      ['--b', 'var(--c)'],
      ['--c', 'var(--a)'],
    ]);
    expect([...tokenClosure(['--a', '--a'], [scope])].sort()).toEqual(['--a', '--b', '--c']);
  });

  // Breaks if someone lists a selector twice and the rule is emitted twice.
  it('THEME_SELECTORS has no duplicates', () => {
    expect(new Set(THEME_SELECTORS).size).toBe(THEME_SELECTORS.length);
  });
});
