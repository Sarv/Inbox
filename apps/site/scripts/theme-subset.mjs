// Cuts the few sarv_theme pieces the download page uses out of the full design
// system, verbatim. Pure: CSS text in, CSS text out; sync-theme.mjs does the
// file I/O.
//
// Why a subset and not the whole file: this repository is public and
// sarv_theme is not. Publishing only what one page needs keeps the rest of the
// design system private, and the page ~10x lighter.
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
import valueParser from 'postcss-value-parser';

// The sarv_theme rules the page uses, by their exact selector in
// design-system.css. Add one here when render.js or index.html starts using a
// new component class, then run `pnpm --filter @sarvinbox/site sync-theme`.
export const THEME_SELECTORS = Object.freeze([
  '*',
  'html, body',
  'body',
  'a',
  'a:hover',
  '.btn',
  '.btn:focus-visible',
  '.btn-primary',
  '.btn-primary:hover',
  '.btn-secondary',
  '.btn-secondary:hover',
  '.btn-sm',
  '.btn-lg',
  '.card',
  '.card-pad',
  '.badge',
  '.badge.brand',
  '.banner',
  '.banner.warning',
  '.muted',
  '.row',
  '.stack',
  '.stack-2',
  '.text-sm',
]);

// Where sarv_theme defines the tokens the page takes. Only the light values:
// the download page is light-only by design, so sarv_theme's `.dark`
// overrides are left behind with the rest.
const TOKEN_SCOPES = Object.freeze([':root']);

/** Every custom property a stylesheet reads through var(). */
export const referencedTokens = (root) => {
  const names = new Set();
  root.walkDecls((decl) =>
    valueParser(decl.value).walk((node) => {
      if (node.type === 'function' && node.value === 'var' && node.nodes[0])
        names.add(node.nodes[0].value);
    })
  );
  return names;
};

/** Every class name a stylesheet's selectors mention. */
export const definedClasses = (root) => {
  const names = new Set();
  root.walkRules((rule) =>
    selectorParser((selectors) =>
      selectors.walkClasses((node) => names.add(node.value))
    ).processSync(rule.selector)
  );
  return names;
};

const topLevelRules = (root, selector) =>
  root.nodes.filter((node) => node.type === 'rule' && node.selector === selector);

// name -> value for one token scope, later blocks winning as they do in CSS.
const tokenDefinitions = (root, scope) =>
  new Map(
    topLevelRules(root, scope).flatMap((rule) =>
      rule.nodes
        .filter((node) => node.type === 'decl' && node.prop.startsWith('--'))
        .map((decl) => [decl.prop, decl.value])
    )
  );

const tokensInValue = (value) =>
  referencedTokens(postcss.root().append(postcss.decl({ prop: 'x', value })));

/**
 * `seeds` plus every token they reach through other tokens' values, in any
 * scope (e.g. --brand -> var(--color-brand-500)). Throws on a token nobody
 * defines: that would render as an unset value, silently.
 */
export const tokenClosure = (seeds, scopes) => {
  const reached = new Set();
  const pending = [...seeds];
  while (pending.length > 0) {
    const name = pending.pop();
    if (reached.has(name)) continue;
    const values = scopes
      .map((definitions) => definitions.get(name))
      .filter((value) => value !== undefined);
    if (values.length === 0) throw new Error(`sarv_theme defines no ${name}`);
    reached.add(name);
    values.forEach((value) => pending.push(...tokensInValue(value)));
  }
  return reached;
};

const tokenBlock = (scope, definitions, needed) =>
  postcss
    .rule({ selector: scope, raws: { between: ' ', after: '\n' } })
    .append(
      [...definitions]
        .filter(([name]) => needed.has(name))
        .map(([prop, value]) =>
          postcss.decl({ prop, value, raws: { before: '\n  ', between: ': ' } })
        )
    );

const HEADER = `/* GENERATED by scripts/sync-theme.mjs from sarv_theme — do not edit by hand.
   Only the rules the download page uses (THEME_SELECTORS in
   scripts/theme-subset.mjs) and the tokens they reach, copied verbatim. */`;

/**
 * The subset stylesheet. `pageCss` is the page's own stylesheet: the tokens it
 * reads are kept too. Throws when a selector is missing from sarv_theme, so a
 * rename there fails the sync instead of dropping a component's styles.
 */
export const buildThemeSubset = ({
  designSystemCss,
  fontsCss,
  pageCss,
  selectors = THEME_SELECTORS,
}) => {
  const source = postcss.parse(designSystemCss);
  const missing = selectors.filter((selector) => topLevelRules(source, selector).length === 0);
  if (missing.length > 0) throw new Error(`sarv_theme has no rule for: ${missing.join(', ')}`);

  const rules = source.nodes.filter(
    (node) => node.type === 'rule' && selectors.includes(node.selector)
  );
  const scopes = TOKEN_SCOPES.map((scope) => tokenDefinitions(source, scope));
  const seeds = [
    ...referencedTokens(postcss.root().append(rules.map((rule) => rule.clone()))),
    ...referencedTokens(postcss.parse(pageCss)),
  ];
  const needed = tokenClosure(seeds, scopes);

  const imports = postcss
    .parse(fontsCss)
    .nodes.filter((node) => node.type === 'atrule' && node.name === 'import');
  const output = postcss
    .root()
    .append(
      ...[
        ...imports,
        ...TOKEN_SCOPES.map((scope, index) => tokenBlock(scope, scopes[index], needed)),
        ...rules,
      ].map((node) => node.clone({ raws: { ...node.raws, before: '\n\n' } }))
    );
  return `${HEADER}${output.toString()}\n`;
};
